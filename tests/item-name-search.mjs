import assert from 'node:assert/strict';
import {items} from '../src/domain.ts';
import {matchesItemQuery,matchingItems} from '../src/itemSearch.ts';
import {searchSharedOrders} from '../src/sharedPurchasing.ts';
import {resolveReceivingScan} from '../src/purchaseOrderScanning.ts';
for(const q of ['cheese',' CHEESE ','shredded mozz','mozzarella shredded'])assert.ok(matchesItemQuery(items.find(i=>i.sku==='1003'),q),q);
assert.ok(matchesItemQuery(items.find(i=>i.sku==='1004'),'cheese'));
assert.ok(matchesItemQuery(items.find(i=>i.sku==='1030'),'dough'));
assert.ok(!matchesItemQuery(items.find(i=>i.sku==='1003'),'milk'),'milk must not invent a milk item or match cheese');
assert.ok(matchesItemQuery({name:'Whole milk',sku:'MILK',barcode:'REAL-MILK'},'milk'));
assert.equal(matchingItems(items,'SKU 1003')[0].sku,'1003');assert.equal(matchingItems(items,'ZBZ–1007')[0].sku,'1007');
assert.deepEqual(matchingItems([{name:'Other',sku:'9999',barcode:'1003'}],'SKU 1003'),[]);
const milk={sku:'MILK',name:'Whole milk',barcode:'REAL-MILK',made:false};
const d={items:[...items.map(i=>({...i,made:!!i.recipe})),milk],orders:[{id:'a',po_no:'PO-A',supplier_id:'s',status:'Order Sent',expected_at:'2026-11-22'},{id:'b',po_no:'PO-B',supplier_id:'s',status:'Order Sent',expected_at:'2026-11-23'}],suppliers:[{id:'s',name:'Supplier'}],lines:[{id:'line-a',purchase_order_id:'a',item_sku:'1003',quantity_purchase:3,quantity_received_purchase:0},{id:'line-b',purchase_order_id:'b',item_sku:'MILK',quantity_purchase:2,quantity_received_purchase:0}]};
assert.deepEqual(searchSharedOrders(d,'cheese').orders.map(p=>p.id),['a']);
assert.deepEqual(searchSharedOrders(d,'milk').orders.map(p=>p.id),['b']);
assert.ok(searchSharedOrders(d,'dough').items.some(i=>i.sku==='1030'));
assert.equal(searchSharedOrders(d,'dough').orders.length,0);
assert.equal(resolveReceivingScan(d,'shredded mozz').order.id,'a');
assert.equal(resolveReceivingScan(d,'milk').order.id,'b');
assert.equal(resolveReceivingScan(d,'cheese').kind,'none','multiple cheese items must require choosing an item');
assert.match(resolveReceivingScan(d,'dough').message,/made in house/);
const before=JSON.stringify(d);resolveReceivingScan(d,'milk');assert.equal(JSON.stringify(d),before);
console.log('PASS: case-insensitive partial/multiword item names, familiar cheese names, catalog milk, in-house dough, item-name-to-PO lookup, ambiguous-name selection, exact SKU/code priority and zero search mutations.');
